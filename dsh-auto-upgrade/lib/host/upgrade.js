/**
 * 变更半边的调度层：把「停服 → npm install -g → 校验 → 拉起」交给一个
 * **脱离进程的 helper** 去做。
 *
 * 为什么必须脱离：`npm install -g` 覆盖的正是当前宿主正在运行的那棵树，
 * 而"停服"就是杀掉宿主自己。宿主能做的只有三件事：门禁 → 备份 → 落 payload 并
 * fork helper，然后正常退出（exit 0，避免被 KeepAlive 再拉一次）。
 * @module dsh-plugin-auto-upgrade/host/upgrade
 */
import { spawn as nodeSpawn } from 'node:child_process'
import { chmod, mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

import { ALLOW_SCRIPTS, DSH_PACKAGE } from './protocol.js'

/** helper 读的 payload 文件名。 */
export const PAYLOAD_FILE = 'helper-payload.json'
/** helper 写的结果文件名。 */
export const RESULT_FILE = 'result.json'
/** helper 与重启日志文件名。 */
export const LOG_FILE = 'restart.log'
/** 刷新 `url.txt` 的最大重试次数（每次 ≥1s，外加 node 启动与最长 3s 的认证超时）。 */
export const REFRESH_ATTEMPTS = 60

/**
 * 安装命令参数（带安装脚本白名单）。
 * @param {{version:string, allowScripts?:string}} options 输入。
 * @returns {string[]} argv（不含 npm 本身）。
 */
export function installArgs(options) {
  const allow = options.allowScripts ?? ALLOW_SCRIPTS
  return ['install', '-g', `--allow-scripts=${allow}`, `${DSH_PACKAGE}@${options.version}`]
}

/**
 * 安装命令参数（不带白名单，老 npm 不认那个参数时的退路）。
 * @param {{version:string}} options 输入。
 * @returns {string[]} argv。
 */
export function plainInstallArgs(options) {
  return ['install', '-g', `${DSH_PACKAGE}@${options.version}`]
}

/**
 * POSIX shell 单引号转义。
 * @param {unknown} value 任意值。
 * @returns {string} 可直接拼进脚本的字面量。
 */
export function shellQuote(value) {
  return `'${String(value).replace(/'/g, "'\\''")}'`
}

/**
 * 生成 helper 脚本（纯函数，可单测）。
 * @param {object} payload 见模块头部说明。
 * @returns {string} 脚本全文。
 */
export function buildUpgradeScript(payload) {
  const q = shellQuote
  const argsText = payload.args.map((arg) => q(arg)).join(' ')
  const argsDisplay = payload.args.join(' ')
  const lines = [
    '#!/bin/sh',
    '# generated by dsh-plugin-auto-upgrade — do not edit',
    `LOG=${q(payload.logPath)}`,
    `RESULT=${q(payload.resultPath)}`,
    `MODE=${q(payload.mode)}`,
    `HOST_PID=${q(String(payload.hostPid))}`,
    `PORT=${q(String(payload.port))}`,
    `NPM=${q(payload.npm)}`,
    `DSH_BIN=${q(payload.dshBin)}`,
    `PKG=${q(payload.package ?? DSH_PACKAGE)}`,
    `TARGET=${q(payload.target ?? '')}`,
    `CURRENT=${q(payload.current ?? '')}`,
    `BACKUP=${q(payload.backup ?? '')}`,
    `PROFILE=${q(payload.profile ?? '')}`,
    `EXEC=${q(payload.execPath)}`,
    `CWD=${q(payload.cwd)}`,
    `OUT=${q(payload.outLog)}`,
    `SMOKE=${q(payload.smokeOut)}`,
    `REFRESH_SCRIPT=${q(payload.refreshScript ?? '')}`,
    'BASELINE=""',
    `LAUNCHCTL=${q(payload.launchctl ?? '/bin/launchctl')}`,
    `LAUNCHD_LABEL=${q(payload.launchdLabel ?? '')}`,
    'LSDOMAIN="gui/$(id -u)"',
    `ALLOW=${q(payload.allowScripts ?? ALLOW_SCRIPTS)}`,
    `ARGS_DISPLAY=${q(argsDisplay)}`,
    '',
    'say() { printf \'[%s] %s\\n\' "$(date \'+%Y-%m-%d %H:%M:%S\')" "$*" >> "$LOG"; }',
    '',
    'write_result() {',
    '  printf \'{"ok":%s,"mode":"%s","from":"%s","to":"%s","failedStep":%s,"finishedAt":"%s","backup":"%s"}\\n\' \\',
    '    "$1" "$MODE" "$CURRENT" "$TARGET" "$2" "$(date -u \'+%Y-%m-%dT%H:%M:%SZ\')" "$BACKUP" > "$RESULT"',
    '}',
    '',
    'relaunch() {',
    '  say "relaunch: $EXEC $ARGS_DISPLAY (cwd=$CWD)"',
    '  if [ -n "$LAUNCHD_LABEL" ]; then',
    '    if "$LAUNCHCTL" print "$LSDOMAIN/$LAUNCHD_LABEL" >/dev/null 2>&1; then',
    '      say "relaunching through launchd: $LAUNCHD_LABEL"',
    '      if "$LAUNCHCTL" kickstart -k "$LSDOMAIN/$LAUNCHD_LABEL" >> "$LOG" 2>&1; then',
    '        say "kickstart ok"',
    '        return',
    '      fi',
    '      say "kickstart failed; falling back to a detached spawn"',
    '    else',
    '      say "no launchd job named $LAUNCHD_LABEL; using a detached spawn"',
    '    fi',
    '  fi',
    '  cd "$CWD" 2>/dev/null || true',
    `  nohup "$EXEC" ${argsText} >> "$OUT" 2>&1 &`,
    '  say "relaunched as pid $!"',
    '}',
    '',
    'port_busy() {',
    '  command -v lsof >/dev/null 2>&1 || return 1',
    '  [ -n "$(lsof -tiTCP:"$PORT" -sTCP:LISTEN 2>/dev/null)" ]',
    '}',
    '',
    'say "helper start (mode=$MODE current=$CURRENT target=$TARGET pid=$$)"',
    '',
    '# `.dsh-web/url.txt` carries the launch token, which is process-scoped and',
    '# only ever printed to stdout. Under launchd that stdout is the job log, so',
    '# read the path back from launchctl instead of assuming a file location.',
    'resolve_log_path() {',
    '  LOG_PATH="$OUT"',
    '  if [ -n "$LAUNCHD_LABEL" ] && [ -x "$LAUNCHCTL" ]; then',
    '    LP=$("$LAUNCHCTL" print "$LSDOMAIN/$LAUNCHD_LABEL" 2>/dev/null | sed -n "s/.*stdout path = //p" | head -n 1)',
    '    if [ -n "$LP" ]; then LOG_PATH="$LP"; fi',
    '  fi',
    '}',
    '',
    '# BASELINE holds the last token URL from BEFORE the relaunch (issue #293):',
    '# refresh-url.mjs only accepts a URL that is newer than it AND authenticates,',
    '# so a not-yet-restarted log can never overwrite url.txt with a dead token.',
    'refresh_url() {',
    '  [ -n "$REFRESH_SCRIPT" ] || return 1',
    '  resolve_log_path',
    '  [ -n "$LOG_PATH" ] && [ -f "$LOG_PATH" ] || return 1',
    '  URL_FILE="$(dirname "$LOG_PATH")/url.txt"',
    '  "$EXEC" "$REFRESH_SCRIPT" --previous "$BASELINE" "$LOG_PATH" "$URL_FILE" >> "$LOG" 2>&1',
    '}',
    '',
    'i=0',
    'while [ "$i" -lt 60 ]; do',
    '  kill -0 "$HOST_PID" 2>/dev/null || break',
    '  sleep 1',
    '  i=$((i+1))',
    'done',
    'if kill -0 "$HOST_PID" 2>/dev/null; then',
    '  say "host $HOST_PID did not exit in 60s; sending SIGTERM"',
    '  kill -TERM "$HOST_PID" 2>/dev/null || true',
    '  sleep 3',
    '  if kill -0 "$HOST_PID" 2>/dev/null; then',
    '    say "host still alive; sending SIGKILL"',
    '    kill -9 "$HOST_PID" 2>/dev/null || true',
    '    sleep 1',
    '  fi',
    'fi',
    'say "host is gone"',
    '',
    'i=0',
    'while [ "$i" -lt 30 ] && port_busy; do',
    '  sleep 1',
    '  i=$((i+1))',
    'done',
    'if port_busy; then say "port $PORT still busy; continuing anyway"; else say "port $PORT is free"; fi',
    '',
    'if [ "$MODE" != "restart" ]; then',
    '  say "installing $PKG@$TARGET"',
    '  "$NPM" install -g "--allow-scripts=$ALLOW" "$PKG@$TARGET" >> "$LOG" 2>&1',
    '  CODE=$?',
    '  if [ "$CODE" -ne 0 ]; then',
    '    say "install with --allow-scripts failed (exit $CODE); retrying without it"',
    '    "$NPM" install -g "$PKG@$TARGET" >> "$LOG" 2>&1',
    '    CODE=$?',
    '  fi',
    '  if [ "$CODE" -ne 0 ]; then',
    '    say "install failed with exit $CODE"',
    '    DISK=$("$DSH_BIN" --version 2>/dev/null | tr -d "\\r" | tail -n 1)',
    '    if [ "$DISK" = "$CURRENT" ]; then',
    '      say "on-disk tree is still $CURRENT; relaunching it"',
    '    else',
    '      say "on-disk version is ${DISK:-<empty>}; reinstalling $CURRENT"',
    '      "$NPM" install -g "$PKG@$CURRENT" >> "$LOG" 2>&1 || say "reinstall of $CURRENT failed"',
    '    fi',
    '    write_result false \'"install"\'',
    '    relaunch',
    '    exit 1',
    '  fi',
    '  say "install finished"',
    '',
    '  GOT=$("$DSH_BIN" --version 2>/dev/null | tr -d "\\r" | tail -n 1)',
    '  say "dsh --version -> ${GOT:-<empty>} (expected $TARGET)"',
    '  if [ "$GOT" != "$TARGET" ]; then',
    '    say "version mismatch; NOT restarting the service, so a broken tree cannot serve the UI"',
    '    say "manual rollback: $NPM install -g $PKG@$CURRENT"',
    '    write_result false \'"verify"\'',
    '    exit 1',
    '  fi',
    '',
    '  if "$DSH_BIN" --profile "$PROFILE" --dump-default-config > "$SMOKE" 2>&1; then',
    '    say "profile smoke test passed"',
    '  else',
    '    say "profile smoke test FAILED (see $SMOKE); NOT restarting the service"',
    '    say "manual rollback: $NPM install -g $PKG@$CURRENT"',
    '    write_result false \'"smoke"\'',
    '    exit 1',
    '  fi',
    'fi',
    '',
    '# Capture the pre-relaunch baseline FIRST (issue #293): right after kickstart',
    '# the new host has not printed its URL yet, so the log still ends with the',
    '# previous start\'s URL. Only presence is logged — never the URL (it holds a token).',
    'if [ -n "$REFRESH_SCRIPT" ]; then',
    '  resolve_log_path',
    '  if [ -f "$LOG_PATH" ]; then BASELINE=$("$EXEC" "$REFRESH_SCRIPT" --print-latest "$LOG_PATH" 2>/dev/null || true); fi',
    '  if [ -n "$BASELINE" ]; then say "baseline: log already has a token URL"; else say "baseline: no token URL in log yet"; fi',
    'fi',
    '',
    'write_result true null',
    'relaunch',
    '',
    '# Give the relaunched host a moment to print its URL, then refresh url.txt.',
    '# Exhaustion must NOT look like success (issue #293): a silent `done` after a',
    '# failed refresh is the same class of failure this fix exists to remove.',
    'if [ -n "$REFRESH_SCRIPT" ]; then',
    '  REFRESHED=0',
    '  i=0',
    `  while [ "$i" -lt ${REFRESH_ATTEMPTS} ]; do`,
    '    if refresh_url; then REFRESHED=1; break; fi',
    '    sleep 1',
    '    i=$((i+1))',
    '  done',
    '  if [ "$REFRESHED" -eq 1 ]; then',
    '    say "url.txt refreshed"',
    '  else',
    `    say "WARNING: url.txt was NOT refreshed (no new token URL authenticated within ${REFRESH_ATTEMPTS} retries); open the newest line of the log instead: grep 'dsh web: http' $OUT | tail -1"`,
    '  fi',
    'fi',
    'say "done"',
    'exit 0',
    '',
  ]
  return lines.join('\n')
}

/**
 * 落 payload + 脚本，并 fork 一个脱离进程的 helper。
 * @param {{stateDir:string, payload:object, spawn?:Function}} options 输入。
 * @returns {Promise<{scriptPath:string, payloadPath:string, pid:number|undefined}>} 调度结果。
 */
export async function scheduleHelper(options) {
  const spawn = options.spawn ?? nodeSpawn
  const payloadPath = join(options.stateDir, PAYLOAD_FILE)
  const scriptPath = join(options.stateDir, options.payload.mode === 'restart' ? 'relaunch.sh' : 'upgrade.sh')
  // 状态目录可能还不存在：helper 要往里面写日志与结果，必须先建出来。
  await mkdir(options.stateDir, { recursive: true })
  await writeFile(payloadPath, `${JSON.stringify(options.payload, null, 2)}\n`, 'utf8')
  await writeFile(scriptPath, buildUpgradeScript(options.payload), 'utf8')
  await chmod(scriptPath, 0o700)
  const child = spawn('/bin/sh', [scriptPath], {
    detached: true,
    stdio: 'ignore',
    cwd: options.stateDir,
  })
  child.unref?.()
  return { scriptPath, payloadPath, pid: child.pid }
}

/**
 * 读 helper 写下的结果。
 * @param {string} stateDir 状态目录。
 * @returns {Promise<object|undefined>} 结果对象；没有或坏了返回 undefined。
 */
export async function readResult(stateDir) {
  return readJson(join(stateDir, RESULT_FILE))
}

/**
 * 读最近一次调度给 helper 的 payload（给面板回显"正在做什么"）。
 * @param {string} stateDir 状态目录。
 * @returns {Promise<object|undefined>} payload；没有或坏了返回 undefined。
 */
export async function readPayload(stateDir) {
  return readJson(join(stateDir, PAYLOAD_FILE))
}

/**
 * 读一个 JSON 文件。
 * @param {string} path 文件路径。
 * @returns {Promise<object|undefined>} 解析结果。
 */
async function readJson(path) {
  try {
    const parsed = JSON.parse(await readFile(path, 'utf8'))
    return parsed !== null && typeof parsed === 'object' ? parsed : undefined
  } catch {
    return undefined
  }
}
